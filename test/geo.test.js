const close = (a, b, eps = 1e-9) => Math.abs(a - b) < eps;

// ---------------------------------------------------------------- the projection
test('the map is the whole world east to west, and its corners are the corners of the box', () => {
  assert.deepEqual(project(LAT_MAX, LON_MIN), { x: 0, y: 0 });
  const bottomRight = project(LAT_MIN, LON_MAX);
  assert.ok(close(bottomRight.x, 1) && close(bottomRight.y, 1));
  assert.ok(close(project(0, 0).x, 0.5), 'the prime meridian is in the middle');
  assert.equal(WIDTH, 1000);
  assert.ok(HEIGHT > 480 && HEIGHT < 520, `about 2:1, not ${WIDTH} x ${HEIGHT}`);
});

test('east is right and north is up, everywhere', () => {
  for (const lat of [-50, -20, 0, 30, 60, 80]) for (let lon = -170; lon < 170; lon += 20) {
    assert.ok(project(lat, lon + 10).x > project(lat, lon).x, `${lat}, ${lon}`);
    assert.ok(project(lat + 4, lon).y < project(lat, lon).y, `${lat}, ${lon}`);
  }
  assert.ok(millerY(60) > millerY(30) && millerY(30) > millerY(0), 'Miller stretches toward the poles');
});

test('a place outside the map\'s latitudes is pinned to its edge rather than dropped off it', () => {
  assert.equal(project(-89, 10).y, 1);
  assert.equal(project(89, 10).y, 0);
  assert.equal(project(10, 999).x, 1);
  assert.equal(project(10, -999).x, 0);
});

test('the marker position and the drawing position are the same place', () => {
  const p = project(35.7, 139.7), d = toDrawing(35.7, 139.7);
  assert.ok(close(d.x, p.x * WIDTH) && close(d.y, p.y * HEIGHT));
});

