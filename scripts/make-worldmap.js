'use strict';
/*
 * Draws the land for the Overview's world map: web/app/worldmap.js.
 *
 * The source is Natural Earth's 1:110m land outlines (scripts/data/ne_110m_land.geojson), which are in the public
 * domain (naturalearthdata.com). Nothing is fetched at run time and there is no tile service: the outline is a single
 * SVG path, projected with the same function that places each region's marker (server/lib/geo.js).
 *
 * `npm run worldmap` rewrites the file. test/geo.test.js fails if the committed file differs from what this
 * script would produce.
 */

const fs = require('node:fs');
const path = require('node:path');
const { toDrawing, WIDTH, HEIGHT, LAT_MIN } = require('../server/lib/geo');

const ROOT = path.resolve(__dirname, '..');
const SOURCE = path.join(__dirname, 'data', 'ne_110m_land.geojson');
const OUT = path.join(ROOT, 'web', 'app', 'worldmap.js');

const round = (x) => Math.round(x * 10) / 10;
const MIN_STEP = 0.35;                     // points closer than this (in drawing units) add nothing the eye can see

function build() {
  const geo = JSON.parse(fs.readFileSync(SOURCE, 'utf8'));
  const polygons = [];
  for (const f of geo.features) {
    if (f.geometry.type === 'Polygon') polygons.push(f.geometry.coordinates);
    else if (f.geometry.type === 'MultiPolygon') polygons.push(...f.geometry.coordinates);
  }
  let d = '';
  let kept = 0;
  for (const rings of polygons) {
    const maxLat = Math.max(...rings.flat().map((p) => p[1]));
    if (maxLat < LAT_MIN) continue;                          // wholly south of the map: Antarctica
    for (const ring of rings) {
      const pts = [];
      for (const [lon, lat] of ring) {
        const p = toDrawing(lat, lon);
        const last = pts[pts.length - 1];
        if (!last || Math.hypot(p.x - last.x, p.y - last.y) >= MIN_STEP) pts.push(p);
      }
      if (pts.length < 3) continue;
      d += `M${pts.map((p) => `${round(p.x)},${round(p.y)}`).join('L')}Z`;
    }
    kept++;
  }
  const body = `(function () { window.LAB_WORLDMAP = ${JSON.stringify({ width: WIDTH, height: HEIGHT, d })}; })();\n`;
  return {
    polygons: kept,
    text: `/* Generated by scripts/make-worldmap.js from Natural Earth 1:110m land (public domain, naturalearthdata.com). Do not edit. */\n${body}`,
  };
}

if (require.main === module) {
  const { text, polygons } = build();
  fs.writeFileSync(OUT, text);
  console.log(`worldmap: wrote web/app/worldmap.js (${(Buffer.byteLength(text) / 1024).toFixed(0)} KB, ${polygons} land outlines, ${WIDTH} x ${HEIGHT})`);
}

module.exports = { build };
